const assert=require('node:assert/strict');
require('../lib.js');require('../analytics.js');require('../sync-core.js');
const Core=global.TimeLensCore,A=global.TimeLensAnalytics;
const site=(ms,hourly)=>({durationMs:ms,visits:1,title:'Example',url:'https://example.com',...(hourly?{hourlyMs:hourly}:{})});
const stats={'2026-10-19':{'example.com':site(60000)}};
const week=A.timeline(stats,'2026-10-19','2026-10-25','2026-10-19','weekly');
assert.equal(week.length,7);assert.equal(week[0].durationMs,60000);assert.equal(week.filter(d=>d.future).length,6);
assert.equal(week[0].missing,false);assert.equal(week[1].missing,false);
assert.equal(A.timeline({},'2026-10-12','2026-10-18','2026-10-19','weekly').filter(d=>d.missing).length,7);
assert.equal(A.timeline(stats,'2026-10-01','2026-10-31','2026-10-19','monthly').length,31);
const year=A.timeline(stats,'2026-01-01','2026-12-31','2026-10-19','yearly');
assert.equal(year.length,12);assert.equal(year[9].durationMs,60000);assert.equal(year[10].future,true);
assert.equal(A.timeline({},'2024-01-01','2024-03-31','2026-10-19','quarterly').length,91);
const history={'2026-06-30':{'example.com':site(3600000)},'2026-07-01':{'example.com':site(7200000)}};
assert.deepEqual(A.patterns(history,'2026-06-30','2026-07-01','monthly').available,['sites']);
const annual=A.patterns(history,'2026-01-01','2026-10-19','yearly');
assert.deepEqual(annual.available,['weekday','academic','sites']);
assert.equal(annual.academic.find(p=>p.kind==='spring').averageMs,3600000);
assert.equal(annual.academic.find(p=>p.kind==='summer').averageMs,7200000);
assert.equal(annual.missingDays,Core.enumerateDates('2026-01-01','2026-10-19').length-2);
assert.equal(A.patterns(history,'2026-06-29','2026-07-05','weekly').available.includes('academic'),false);
assert.equal(A.classify('2027-07-19'),'summer');
assert.equal(A.classify('2025-02-01'),'winter');
assert.equal(A.classify('2026-01-31'),'autumn');
assert.equal(A.patterns(stats,'2026-10-19','2026-10-19','weekly').available.length,0);
const hours=Array(24).fill(0);hours[9]=60000;
const granular={'2026-10-18':{'example.com':site(60000,hours)},'2026-10-19':{'example.com':site(60000,hours)}};
assert.equal(A.patterns(granular,'2026-10-18','2026-10-19','monthly').hours[9].averageMs,60000);
assert.ok(A.patterns(granular,'2026-10-18','2026-10-19','monthly').available.includes('hourly'));
const hourly=A.timeline(granular,'2026-10-19','2026-10-19','2026-10-19','daily',new Date(2026,9,19,12));
assert.equal(hourly.length,24);assert.equal(hourly[9].durationMs,60000);
assert.equal(hourly[10].missing,true);assert.equal(hourly[13].future,true);
assert.equal(A.timeline(history,'2026-06-30','2026-06-30','2026-10-19','daily').length,1);
const old=JSON.stringify(history);
const normalized=Core.normalizeDailyStats(granular);
assert.deepEqual(normalized['2026-10-18']['example.com'].hourlyMs,hours);
const merged=Core.mergeDailyStats(normalized,normalized);
assert.equal(merged['2026-10-18']['example.com'].hourlyMs[9],120000);
assert.equal(global.TimeLensSyncCore.stats(normalized,{other:{dailyStats:normalized}})['2026-10-18']['example.com'].hourlyMs[9],120000);
assert.equal(JSON.stringify(history),old);
console.log('analytics.test.js: complete calendar axes, eligibility, missing dates, academic boundaries and hourly synchronization passed');
